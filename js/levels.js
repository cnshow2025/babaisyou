  // 把關卡地圖轉成引擎可用的物體清單。
  function parseLevel(level) {
    const objs = [];
    const h = level.map.length;
    const w = Math.max(...level.map.map(r => r.length));
    level.map.forEach((row, y) => {
      [...row].forEach((ch, x) => {
        if (ch === '.' || ch === ' ') return;
        if (OBJECTS[ch]) objs.push({ type: OBJECTS[ch], x, y });
        else if (WORDS[ch]) objs.push({ type: 'text', word: WORDS[ch], x, y });
        else throw new Error(`關卡「${level.name}」有未知字元 '${ch}'`);
      });
    });
    return { w, h, objs };
  }

  const api = { LEVELS, OBJECTS, WORDS, parseLevel };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.BabaLevels = api;
